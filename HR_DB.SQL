-- ✅ STEP 1: Create Environment

CREATE DATABASE HR_DB;
USE DATABASE HR_DB;

CREATE SCHEMA HR;
USE SCHEMA HR;

-- ✅ STEP 2: Create STAGE TABLE (Raw Data)

CREATE OR REPLACE TABLE EMP_STAGE(
EMPLOYEE_ID INT,
FIRST_NAME STRING,
SALARY NUMBER,
DEPARTMENT_ID INT
);


-- ✅ STEP 3: Create DIM TABLE (SCD Type 2)

CREATE OR REPLACE TABLE EMP_DIM(
EMPLOYEE_ID INT,
FIRST_NAME STRING,
SALARY NUMBER,
DEPARTMENT_ID INT,
START_DATE DATE, 
END_DATE DATE, 
CURRENT_FLAG INT
);


-- ✅ STEP 4: Insert Initial Data

INSERT INTO EMP_STAGE VALUES 
(101, 'JOHN', 5000, 10),
(102, 'ALICE', 6000, 20);


-- ✅ STEP 5: Initial Load into DIM

INSERT INTO EMP_DIM 
SELECT 
EMPLOYEE_ID, FIRST_NAME, SALARY, DEPARTMENT_ID, CURRENT_DATE, NULL, 1
FROM EMP_STAGE;


-- ✅ STEP 6: Simulate Data Change
-- 👉 Now simulate update (real world scenario)

TRUNCATE TABLE EMP_STAGE;

INSERT INTO EMP_STAGE VALUES
(101, 'JOHN', 7000, 10),  --SALARY CHANGED
(102, 'ALICE', 6000, 20),  --SAME
(103, 'BOB', 4000, 30);  --NEW EMPLOYEE



-- ✅ STEP 7: Apply SCD TYPE 2 (CORE LOGIC 🔥)

-- 🔹 Step 7.1: Close old records

UPDATE EMP_DIM T 
SET END_DATE = CURRENT_DATE,
CURRENT_FLAG = 0
FROM EMP_STAGE S
WHERE T.EMPLOYEE_ID = S.EMPLOYEE_ID AND T.SALARY <> S.SALARY AND T.CURRENT_FLAG = 1;

-- 🔹 Step 7.2: Insert new + changed records

INSERT INTO EMP_DIM (
EMPLOYEE_ID,
FIRST_NAME,
SALARY,
DEPARTMENT_ID, 
START_DATE,
END_DATE,
CURRENT_FLAG
)
SELECT S.EMPLOYEE_ID, 
S.FIRST_NAME,
S.SALARY,
S.DEPARTMENT_ID,
CURRENT_DATE,
NULL, 
1
FROM EMP_STAGE S 
LEFT JOIN EMP_DIM T 
ON S.EMPLOYEE_ID = T.EMPLOYEE_ID AND T.CURRENT_FLAG = 1
WHERE T.EMPLOYEE_ID IS NULL OR T.SALARY <> S.SALARY;



-- ✅ STEP 8: Verify Output
SELECT * FROM EMP_DIM 
ORDER BY EMPLOYEE_ID, START_DATE;


-- ✅ STEP 9: Add STREAM (Change Tracking 🔥)

CREATE OR REPLACE STREAM EMP_STREAM ON TABLE EMP_STAGE;

-- 👉 Now Snowflake tracks:
-- ✅ Inserts
-- ✅ Updates
-- ✅ Deletes

CREATE OR REPLACE TASK EMP_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = '1 MINUTE'
AS
INSERT INTO EMP_DIM
SELECT 
    EMPLOYEE_ID,
    FIRST_NAME,
    SALARY,
    DEPARTMENT_ID,
    CURRENT_DATE,
    NULL,
    1
FROM EMP_STREAM;

